import { NextResponse } from 'next/server';
import { requireAuth } from '@/lib/auth';
import { query } from '@/lib/db';

export async function GET() {
  try {
    await requireAuth(['FACILITY_MANAGER']);

    // 1. Transaction evidence from asset_maintenance_ledger
    const ledgerRes = await query(`
      SELECT 
        l.id, l.event_type, l.details, l.created_at,
        a.asset_tag, a.name AS asset_name,
        p.full_name AS previous_assignee_name,
        n.full_name AS new_assignee_name,
        u.full_name AS performed_by_name
      FROM asset_maintenance_ledger l
      JOIN assets a ON l.asset_id = a.id
      LEFT JOIN users p ON l.previous_assignee_id = p.id
      LEFT JOIN users n ON l.new_assignee_id = n.id
      JOIN users u ON l.performed_by_user_id = u.id
      ORDER BY l.created_at DESC
      LIMIT 10;
    `);

    // 2. Trigger evidence: automatic notifications generated by PostgreSQL trigger
    const triggerNotifs = await query(`
      SELECT 
        n.id, n.type, n.message, n.dedupe_key, n.created_at,
        a.asset_tag, a.name AS asset_name
      FROM notifications n
      LEFT JOIN assets a ON n.asset_id = a.id
      WHERE n.type IN ('WARRANTY_EXPIRING', 'WARRANTY_EXPIRED')
      ORDER BY n.created_at DESC
      LIMIT 10;
    `);

    // 3. View evidence: real rows from critical_asset_dashboard view
    const viewRes = await query(`
      SELECT * FROM critical_asset_dashboard
      ORDER BY days_remaining ASC NULLS LAST
      LIMIT 10;
    `);

    // 4. pgvector status and statistics
    const extRes = await query("SELECT extname, extversion FROM pg_extension WHERE extname = 'vector';");
    const recordCountRes = await query(`
      SELECT 
        COUNT(*)::INT as total_records,
        COUNT(embedding)::INT as embedded_records
      FROM maintenance_records;
    `);

    return NextResponse.json({
      success: true,
      pgvector: {
        installed: extRes.rows.length > 0,
        version: extRes.rows[0]?.extversion || 'Not installed',
        model_name: 'onnx-community/all-MiniLM-L6-v2-ONNX',
        dimensions: 384,
        index_type: 'HNSW (Hierarchical Navigable Small World, vector_cosine_ops)',
        distance_metric: 'Cosine Distance (<=>)',
        total_records: recordCountRes.rows[0]?.total_records || 0,
        embedded_records: recordCountRes.rows[0]?.embedded_records || 0,
      },
      critical_view_data: viewRes.rows,
      trigger_notifications: triggerNotifs.rows,
      ledger_transactions: ledgerRes.rows,
    });
  } catch (err: any) {
    if (err.message === 'UNAUTHORIZED' || err.message === 'FORBIDDEN') {
      return NextResponse.json({ error: 'Access denied. Facility Managers only.' }, { status: 403 });
    }
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
